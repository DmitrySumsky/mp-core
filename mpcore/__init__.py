"""mp-core — общее ядро сборщиков цен, позиций и статистики маркетплейсов.

Библиотека собрана из кода, который в разных проектах был написан по
пять-восемь раз: обход публичной витрины, клиент платной аналитики,
раскладка «строка = сущность, столбец = дата», ретраи и оповещения.
Расхождение копий стоит дорого — умение, дописанное в одном проекте, не
доезжает до соседнего, и там та же поломка ждёт своего часа.

Модули:

* `http` — ретраи и различение отказов (транзиентный / квота / пустой);
* `transport` — чем ходить в сеть: сессия `requests`, если есть, иначе `urllib`;
* `states` — три состояния замера, которые нельзя смешивать;
* `wb_card` — живая цена с публичной витрины (без ключа и без квоты);
* `mpstats` — история цен из платной аналитики (окно 30 дней, квоты по
  контурам считаются раздельно);
* `datesheet` — чистая логика листа с датами: шапка, вставка, пропуски;
* `sheets` — тонкий клиент Google Sheets с ретраями и лимитом записи;
* `notify` — оповещения с нарезкой и адресной шапкой.

Совместимость: библиотека версионируется по semver, потребители
закрепляются на теге. Ломающее изменение — мажорная версия, и до неё
никто не переезжает без правки своего кода.
"""

