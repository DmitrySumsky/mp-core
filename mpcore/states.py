"""Состояния замера — три разных факта, которые нельзя смешивать.

Пустая ячейка в таблице не отвечает на вопрос «почему её нет». Практика
показала три разные причины, и путать их дорого:

* товар есть, но предложения нет («нет в наличии») — факт о товаре;
* карточки нет вовсе («нет карточки») — факт об артикуле;
* запрос не прошёл («ошибка сбора») — факт о ЗАМЕРЕ, а не о товаре.

Последнее в таблицу писать нельзя: дырка замера, записанная как значение,
навсегда притворится фактом. Правило: `FAIL` в ячейку не идёт, ячейка
остаётся такой, какой была.
"""

STATE_NONE = "нет в наличии"
STATE_GONE = "нет карточки"
STATE_FAIL = "ошибка сбора"

ALL = (STATE_NONE, STATE_GONE, STATE_FAIL)

#: Состояния, которые допустимо записать в ячейку.
WRITABLE = (STATE_NONE, STATE_GONE)


def is_state(value) -> bool:
    """Значение — служебное состояние, а не число."""
    return isinstance(value, str) and value in ALL


def is_price(value) -> bool:
    """Значение — настоящий замер (число), а не состояние и не пустота."""
    return isinstance(value, int) and not isinstance(value, bool)


def writable(value):
    """То, что можно положить в ячейку: число, писчее состояние или None.

    `None` означает «не трогать ячейку» — так же трактуется `STATE_FAIL`.
    """
    if is_price(value):
        return value
    if value in WRITABLE:
        return value
    return None
