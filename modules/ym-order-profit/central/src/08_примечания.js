/**
 * В строке «Формула:» к букве колонки дописывается её короткое название: «AI − AJ» → «AI «Маржа» − AJ «Налог 25%»».
 * Короткое название — заголовок до первой запятой или скобки. Диапазоны (R:Z) и слова из 3+ букв (API, FBS) не трогаются.
 */
function yopNamed_(notes, head) {
  var names = {};
  head.forEach(function (h, i) { names[yopCol_(i + 1)] = String(h).split(/[,(]/)[0].trim(); });
  return notes.map(function (n) {
    return String(n).split('\n').map(function (line) {
      if (line.indexOf('Формула: ') !== 0) return line;
      return line.replace(/(^|[^A-Za-z:«])([A-Z]{1,2})(?![A-Za-z:])/g, function (m, pre, c) {
        return names[c] ? pre + c + ' «' + names[c] + '»' : m;
      });
    }).join('\n');
  });
}

/** Примечания на строку заголовков листа. Сбой примечаний не должен ронять прогон. */
function yopPutNotes_(sh, notes, head) {
  try {
    sh.getRange(YOP_HEAD_ROW, 1, 1, notes.length).setNotes([head ? yopNamed_(notes, head) : notes]);
  } catch (e) { yopLog_('примечания «' + sh.getName() + '»: ' + e.message); }
}
