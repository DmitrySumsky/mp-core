/** Примечания юнитки в порядке колонок. */
function yopUnitNotes_() {
  var idx = {};
  YOP_UNIT_SPEC.forEach(function (c, i) { idx[c[0]] = yopCol_(i + 1); });
  var m = yopUnitNoteMap_(function (k) { return idx[k] || '?'; });
  return YOP_UNIT_SPEC.map(function (c) { return m[c[0]] || ''; });
}

